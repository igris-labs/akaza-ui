import { expect, test } from '@playwright/test'

test('custom formatting toolbar keeps one Tab stop and activates only on press', async ({ page }) => {
  await page.goto('/composables/use-roving-focus')
  const toolbar = page.getByRole('toolbar', { name: 'Text formatting' })
  const bold = toolbar.getByRole('button', { name: 'Bold' })
  const italic = toolbar.getByRole('button', { name: 'Italic' })
  const underline = toolbar.getByRole('button', { name: 'Underline' })

  await expect(page.getByRole('button', { name: 'Search documentation', exact: true }).filter({ visible: true })).toBeEnabled()
  await bold.click()
  await expect(bold).toHaveAttribute('aria-pressed', 'true')
  await bold.focus()
  await expect(bold).toHaveAttribute('tabindex', '0')
  await expect(toolbar.locator('[tabindex="0"]')).toHaveCount(1)
  await page.keyboard.press('ArrowRight')
  await expect(italic).toBeFocused()
  await expect(italic).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.press('Space')
  await expect(italic).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('End')
  await expect(underline).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(underline).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('ArrowRight')
  await expect(bold).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(italic).toBeFocused()
  await page.keyboard.press('Home')
  await expect(bold).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(italic).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(toolbar.locator(':focus')).toHaveCount(0)
  await page.keyboard.press('Shift+Tab')
  await expect(italic).toBeFocused()
  await expect(toolbar.locator('[tabindex="0"]')).toHaveCount(1)
  await toolbar.evaluate(element => element.setAttribute('dir', 'rtl'))
  await page.keyboard.press('ArrowRight')
  await expect(bold).toBeFocused()
})
