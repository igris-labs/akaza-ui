import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { openPlayground, section } from "./helpers";

test.beforeEach(async ({ page }) => openPlayground(page));

test("guarded Listbox rejects highlight/range moves without changing focus or page scroll", async ({ page }) => {
  const demo = section(page, "listbox");
  const list = demo.getByRole("listbox", { name: "Guarded permissions" });
  await list.scrollIntoViewIfNeeded();
  await page.mouse.move(0, 0);
  await list.focus();
  const read = list.getByRole("option", { name: "Read records", exact: true });
  const edit = list.getByRole("option", { name: "Edit records", exact: true });
  await expect(list).toHaveAttribute("aria-activedescendant", (await read.getAttribute("id"))!);
  const scroll = await page.evaluate(() => window.scrollY);
  await page.keyboard.press("Shift+ArrowDown");
  await page.keyboard.press("Shift+ArrowDown");
  await expect(list).toBeFocused();
  await expect(read).toHaveAttribute("aria-selected", "true");
  await expect(edit).toHaveAttribute("aria-selected", "false");
  await expect(list).toHaveAttribute("aria-activedescendant", (await read.getAttribute("id"))!);
  expect(await page.evaluate(() => window.scrollY)).toBe(scroll);
  await demo.getByRole("button", { name: "Allow edit highlight" }).click();
  await page.mouse.move(0, 0);
  await list.focus();
  await page.keyboard.press("Shift+ArrowDown");
  await expect(edit).toHaveAttribute("aria-selected", "true");
  await expect(list).toHaveAttribute("aria-activedescendant", (await edit.getAttribute("id"))!);
  await page.keyboard.press("Shift+ArrowDown");
  await expect(list.locator('[aria-selected="true"]')).toHaveCount(3);
  const result = await new AxeBuilder({ page }).include("#listbox").withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa"]).analyze();
  expect(result.violations.map(({ id, nodes }) => ({ id, targets: nodes.map(node => node.target) }))).toEqual([]);
});

test("virtualized Listbox navigates to unmounted rows without taking DOM focus or forcing manual scroll", async ({ page }) => {
  const list = section(page, "listbox").getByRole("listbox", { name: "Large result set" });
  await list.scrollIntoViewIfNeeded();
  await page.mouse.move(0, 0);
  await list.focus();
  const initial = list.getByRole("option", { name: "Result 43", exact: true });
  await expect(initial).toBeVisible();
  await expect(list).toHaveAttribute("aria-activedescendant", (await initial.getAttribute("id"))!);
  const scroll = await page.evaluate(() => window.scrollY);
  await page.keyboard.press("End");
  const last = list.getByRole("option", { name: "Result 1000", exact: true });
  await expect(last).toBeVisible();
  await expect(list).toHaveAttribute("aria-activedescendant", (await last.getAttribute("id"))!);
  await expect(list).toBeFocused();
  expect(await page.evaluate(() => window.scrollY)).toBe(scroll);
  const bottom = await list.evaluate(element => element.scrollTop);
  const box = await list.boundingBox();
  if (!box) throw new Error("Virtualized listbox has no bounds");
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.wheel(0, -720);
  await expect.poll(() => list.evaluate(element => element.scrollTop)).toBeLessThan(bottom - 100);
  await page.waitForTimeout(200);
  expect(await list.evaluate(element => element.scrollTop)).toBeLessThan(bottom - 100);
  const active = await list.getAttribute("aria-activedescendant");
  if (active) await expect(list.locator(`[id="${active}"]`)).toHaveCount(1);
  await page.mouse.move(0, 0);
  await list.focus();
  await page.keyboard.press("Home");
  const first = list.getByRole("option", { name: "Result 1", exact: true });
  await expect(first).toBeVisible();
  await expect(list).toHaveAttribute("aria-activedescendant", (await first.getAttribute("id"))!);
});

test("horizontal RTL Listbox preserves no-wrap focus and commits only on activation", async ({ page }) => {
  const list = section(page, "listbox").getByRole("listbox", { name: "RTL permissions" });
  await list.scrollIntoViewIfNeeded();
  await page.mouse.move(0, 0);
  await list.focus();
  const read = list.getByRole("option", { name: "Read records", exact: true });
  const edit = list.getByRole("option", { name: "Edit records", exact: true });
  expect(await list.evaluate(element => getComputedStyle(element).direction)).toBe("rtl");
  expect((await read.boundingBox())!.x).toBeGreaterThan((await edit.boundingBox())!.x);
  await page.keyboard.press("ArrowLeft");
  await expect(list).toHaveAttribute("aria-activedescendant", (await edit.getAttribute("id"))!);
  await expect(read).toHaveAttribute("aria-selected", "true");
  await page.keyboard.press("Home");
  await page.keyboard.press("ArrowRight");
  await expect(list).toHaveAttribute("aria-activedescendant", (await read.getAttribute("id"))!);
  await page.keyboard.press("End");
  await page.keyboard.press("Space");
  await expect(list.getByRole("option", { name: "Deploy releases", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(list).toBeFocused();
});

test("ColorSwatchPicker inherits RTL range navigation, disabled skipping, and output formats", async ({ page }) => {
  const demo = section(page, "color-swatch-picker");
  const list = demo.getByRole("listbox", { name: "Multiple colors" });
  await list.scrollIntoViewIfNeeded();
  await page.mouse.move(0, 0);
  await list.focus();
  await page.keyboard.press("Home");
  await page.keyboard.press("Shift+ArrowLeft");
  await expect(list.locator('[aria-selected="true"]')).toHaveCount(2);
  await expect(list.getByRole("option", { name: "Orange", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.keyboard.press("End");
  const purple = list.getByRole("option", { name: "Purple", exact: true });
  await expect(list).toHaveAttribute("aria-activedescendant", (await purple.getAttribute("id"))!);
  await page.keyboard.press("ArrowLeft");
  await expect(list).toHaveAttribute("aria-activedescendant", (await purple.getAttribute("id"))!);
  await page.keyboard.press("Control+a");
  await expect(list.locator('[aria-selected="true"]')).toHaveCount(7);
  await page.keyboard.press("Control+a");
  await expect(list.locator('[aria-selected="true"]')).toHaveCount(7);
  const values = JSON.parse((await demo.locator("output").nth(1).textContent())!);
  expect(values).toHaveLength(7);
  expect(values.every((value: string) => value.startsWith("lch("))).toBe(true);
  await expect(list).toBeFocused();
});
