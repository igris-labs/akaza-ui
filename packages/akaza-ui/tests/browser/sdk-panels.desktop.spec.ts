import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { openPlayground, section } from "./helpers";

test.beforeEach(async ({ page }) => openPlayground(page));

test("Accordion preserves native Tab, RTL arrows, and activation without page jumps", async ({ page, browserName }) => {
  const accordion = section(page, "accordion").getByRole("group", { name: "RTL accordion" });
  const overview = accordion.getByRole("button", { name: "Overview", exact: true });
  const details = accordion.getByRole("button", { name: "Details", exact: true });
  await overview.scrollIntoViewIfNeeded();
  await overview.focus();
  const scroll = await page.evaluate(() => window.scrollY);
  await expect(accordion.getByRole("heading", { level: 3 })).toHaveCount(3);
  await page.keyboard.press("ArrowLeft");
  await expect(details).toBeFocused();
  await expect(details).toHaveAttribute("aria-expanded", "false");
  await page.keyboard.press("ArrowLeft");
  await expect(overview).toBeFocused();
  // WebKit's default keyboard policy uses Option+Tab to include buttons.
  await page.keyboard.press(browserName === "webkit" ? "Alt+Tab" : "Tab");
  await expect(details).toBeFocused();
  await page.keyboard.press(browserName === "webkit" ? "Alt+Shift+Tab" : "Shift+Tab");
  await expect(overview).toBeFocused();
  await page.keyboard.press("Space");
  await expect(overview).toHaveAttribute("aria-expanded", "true");
  await page.keyboard.press("Enter");
  await expect(overview).toHaveAttribute("aria-expanded", "false");
  expect(await page.evaluate(() => window.scrollY)).toBe(scroll);
  const result = await new AxeBuilder({ page }).include("#accordion").withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze();
  expect(result.violations.map(({ id }) => id)).toEqual([]);
});

test("Menu keeps grouped checkbox/radio focus, nested highlights, and keyed reorder", async ({ page }) => {
  const demo = section(page, "menu");
  const trigger = demo.getByRole("button", { name: "Grouped focus commands" });
  await trigger.click();
  await page.mouse.move(0, 0);
  const first = page.getByRole("menuitem", { name: "First command", exact: true });
  await expect(first).toBeFocused();
  const scroll = await page.evaluate(() => window.scrollY);
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("ArrowDown");
  const wrap = page.getByRole("menuitemcheckbox", { name: "Word wrap" });
  await expect(wrap).toBeFocused();
  await page.keyboard.press("Space");
  await expect(wrap).toHaveAttribute("aria-checked", "true");
  await expect(wrap).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("ArrowDown");
  const date = page.getByRole("menuitemradio", { name: "Sort by date" });
  await expect(date).toBeFocused();
  await page.keyboard.press("Space");
  await expect(date).toHaveAttribute("aria-checked", "true");
  await expect(date).toBeFocused();
  const result = await new AxeBuilder({ page }).include(".akaza-menu-content").withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze();
  expect(result.violations.map(({ id }) => id)).toEqual([]);
  await page.keyboard.press("ArrowDown");
  const branch = page.getByRole("menuitem", { name: "Nested commands", exact: true });
  await expect(branch).toBeFocused();
  await page.keyboard.press("ArrowRight");
  const last = page.getByRole("menuitem", { name: "Nested last", exact: true });
  await page.keyboard.press("End");
  await expect(last).toBeFocused();
  await expect(last).toHaveAttribute("data-akaza-highlighted", "");
  await page.keyboard.press("ArrowLeft");
  await expect(branch).toBeFocused();
  await page.keyboard.press("Home");
  await expect(first).toBeFocused();
  await demo.getByRole("button", { name: "Reverse command order" }).evaluate(element => (element as HTMLButtonElement).click());
  await expect(first).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(wrap).toBeFocused();
  await page.keyboard.press("Home");
  await expect(page.getByRole("menuitem", { name: "Last command", exact: true })).toBeFocused();
  expect(await page.evaluate(() => window.scrollY)).toBe(scroll);
  await page.keyboard.press("Escape");
  await expect(trigger).toBeFocused();
});
