import { expect, test } from "@playwright/test";
import { openPlayground, section, tap } from "./helpers";

test("touch selection works independently of roving keyboard focus", async ({ page }) => {
  await openPlayground(page);
  const tabs = section(page, "tabs").getByRole("tablist", { name: "RTL tabs" });
  const analytics = tabs.getByRole("tab", { name: "Analytics" });
  await tap(page, analytics);
  await expect(analytics).toHaveAttribute("aria-selected", "true");
  const radio = section(page, "radio-group").getByRole("radiogroup", { name: "RTL storage" }).getByRole("radio", { name: "HDD", exact: true });
  await tap(page, radio);
  await expect(radio).toHaveAttribute("aria-checked", "true");
  const toggles = section(page, "toggle-group").getByRole("group", { name: "RTL alignment" });
  const center = toggles.getByRole("button", { name: "Center", exact: true });
  await tap(page, center);
  await expect(center).toHaveAttribute("aria-pressed", "true");
  await tap(page, center);
  await expect(center).toHaveAttribute("aria-pressed", "false");
  const toolbar = section(page, "toolbar").getByRole("toolbar", { name: "RTL commands" });
  await tap(page, toolbar.getByRole("button", { name: "Copy", exact: true }));
  await expect(section(page, "toolbar").getByText("action: Copy, query: (empty)", { exact: true })).toBeVisible();
  const steps = section(page, "stepper").getByRole("list", { name: "RTL steps" });
  const workspace = steps.getByRole("button", { name: "Workspace", exact: true });
  await tap(page, workspace);
  await expect(workspace).toHaveAttribute("aria-current", "step");
  const menubar = section(page, "menubar").getByRole("menubar", { name: "RTL application menu" });
  await tap(page, menubar.getByRole("menuitem", { name: "Project", exact: true }));
  await tap(page, page.getByRole("menuitem", { name: "Open project", exact: true }));
  await expect(menubar).toHaveAttribute("data-akaza-state", "closed");
  const navigation = section(page, "navigation-menu").getByRole("navigation", { name: "RTL navigation" });
  const workspaceNavigation = navigation.getByRole("button", { name: "Workspace", exact: true });
  await tap(page, workspaceNavigation);
  await expect(workspaceNavigation).toHaveAttribute("aria-expanded", "true");
  await tap(page, navigation.getByRole("button", { name: "Team", exact: true }));
  await expect(workspaceNavigation).toHaveAttribute("aria-expanded", "false");
});

test("Rating and guarded ToggleGroup support touch without horizontal overflow", async ({ page }) => {
  await openPlayground(page);
  const rating = section(page, "rating").getByRole("radiogroup", { name: "RTL quality" });
  const half = rating.getByRole("radio", { name: "2.5 of 5", exact: true });
  await tap(page, half);
  await expect(half).toHaveAttribute("aria-checked", "true");
  const vertical = section(page, "rating").getByRole("radiogroup", { name: "Vertical quality" });
  const four = vertical.getByRole("radio", { name: "4 of 5", exact: true });
  await tap(page, four);
  await expect(four).toHaveAttribute("aria-checked", "true");
  const group = section(page, "toggle-group").getByRole("group", { name: "Required alignment" });
  const center = group.getByRole("button", { name: "Center", exact: true });
  await tap(page, center);
  await expect(center).toHaveAttribute("aria-pressed", "true");
  await tap(page, center);
  await expect(center).toHaveAttribute("aria-pressed", "true");
  const right = group.getByRole("button", { name: "Right", exact: true });
  await tap(page, right);
  await expect(right).toHaveAttribute("aria-pressed", "false");
  await expect(center).toHaveAttribute("aria-pressed", "true");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
